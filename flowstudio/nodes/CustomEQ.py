# Band names corresponding to the EQ frequency bands
BAND_NAMES = ['band30', 'band60', 'band120', 'band250', 'band500', 'band1K', 'band2K', 'band4K', 'band8K', 'band16K']


@register_node(OP_NODE_CustomEQ)
class FLOW_Node_CustomEQ(FLOW_Node):
    # icon = "icons/in.png"
    op_code = OP_NODE_CustomEQ
    op_title = "Custom_EQ"
    content_label_objname = "Custom_EQ"
    display_name = 'Custom EQ'
    info = ''
    linkType = 1
    type_ao_addition = TypeAOAddition.DYNAMIC_NUM_CHANNELS.value

    def __init__(self, scene, channel):
        self.inputs = []
        self.outputs = []
        for i in range(channel):
            self.inputs.append(1)
            self.outputs.append(1)
        super().__init__(scene, self.inputs, self.outputs)
        self.initControl()
        self.eval()

        self.manager.widgetSet['Presets'].valueChanged.connect(self.on_item_selected)

    def on_item_selected(self):
        text, index = self.manager.widgetSet['Presets'].widget_value

        # Get the preset values for the selected preset
        if text in EQ_PRESETS:
            preset_values = EQ_PRESETS[text]
            
            # Set each band value according to the preset
            for i, band_name in enumerate(BAND_NAMES):
                if i < len(preset_values):
                    self.manager.widgetSet[band_name].widget_value = preset_values[i]
        else:
            print(f"Can't find eq: {text}")

